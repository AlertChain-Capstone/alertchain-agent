test('mobile screens contain overflow and the skip link preserves the route', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  for (const route of ['/', '/incidents', '/incidents/INC-001', '/incidents/INC-001/ask']) {
    await page.goto(`/#${route}`)
    await expect(page.locator('#fa3-content')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.keyboard.press('Tab')
    await page.getByRole('link', { name: 'Skip to content' }).focus()
    await page.keyboard.press('Enter')
    await expect(page.locator('#fa3-content')).toBeFocused()
    expect(new URL(page.url()).hash).toBe(`#${route}`)
  }
})
