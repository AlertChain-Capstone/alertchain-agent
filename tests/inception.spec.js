import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  page.on('pageerror', (error) => { throw error })
})

async function scenario(page, label, option) {
  const control = page.getByLabel(label, { exact: true })
  const details = control.locator('..')
  if (!(await control.isVisible())) await details.locator('summary').click()
  await control.selectOption(option)
}

async function answer(page, question = 'What shows that logging was disabled?') {
  await page.getByRole('button', { name: question, exact: true }).click()
  await page.getByRole('button', { name: 'Ask question', exact: true }).click()
  await expect(page.getByRole('button', { name: 'View citation E2' })).toBeVisible()
}

test('dashboard → filtered incidents → report → answer → citation preserves context', async ({ page }) => {
  await page.goto('/#/')
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  await page.getByRole('link', { name: /Needs human review 1/ }).click()
  await expect(page.getByLabel('Status', { exact: true })).toHaveValue('Needs human review')
  await expect(page.getByText('Showing 1–1 of 1 incidents')).toBeVisible()
  await page.getByRole('link', { name: /Dashboard & Incidents/ }).click()
  await page.getByRole('link', { name: /Open incidents 2/ }).click()
  await expect(page.getByLabel('Status', { exact: true })).toHaveValue('Open')
  await expect(page.getByText('Showing 1–2 of 2 incidents')).toBeVisible()
  await page.getByRole('link', { name: /Dashboard & Incidents/ }).click()
  await page.getByRole('link', { name: 'View all incidents' }).click()
  await expect(page.getByLabel('Status', { exact: true })).toHaveValue('')
  await page.getByLabel('Severity', { exact: true }).selectOption('High')
  await page.getByLabel('Status', { exact: true }).selectOption('Open')
  await expect(page.getByRole('region', { name: 'Incident table' }).getByRole('row')).toHaveCount(3)
  await page.getByRole('link', { name: /INC-001 Leaked/ }).click()
  await page.getByRole('link', { name: 'Ask the Agent', exact: true }).click()
  await answer(page)
  await page.getByRole('button', { name: 'View citation E2' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').getByText('dev-ci-user', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'View citation E2' })).toBeFocused()
  await page.getByRole('link', { name: 'Return to report' }).click()
  await page.getByRole('link', { name: 'Back to incidents' }).click()
  await expect(page.getByLabel('Severity', { exact: true })).toHaveValue('High')
  await expect(page.getByLabel('Status', { exact: true })).toHaveValue('Open')
})

test('pagination, no matches, empty portfolio and retry are distinct', async ({ page }) => {
  await page.goto('/#/incidents')
  await expect(page.getByText('Showing 1–4 of 6 incidents')).toBeVisible()
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(page.getByText('Showing 5–6 of 6 incidents')).toBeVisible()
  await page.getByLabel('Severity', { exact: true }).selectOption('Critical')
  await expect(page.getByRole('heading', { name: 'No matching incidents' })).toBeVisible()
  await scenario(page, 'Incident list demo scenario', 'error')
  await expect(page.getByRole('heading', { name: 'Incidents could not be loaded' })).toBeVisible()
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'No matching incidents' })).toBeVisible()
  await expect(page.getByLabel('Severity', { exact: true })).toHaveValue('Critical')
  await scenario(page, 'Incident list demo scenario', 'empty')
  await expect(page.getByRole('heading', { name: 'No incidents available' })).toBeVisible()
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'No incidents available' })).toBeVisible()
})

